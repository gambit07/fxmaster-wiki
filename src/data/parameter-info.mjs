function displayEffectLabel(effect) {
  return effect.label;
}

function subjectFor(effect) {
  if (effect.kind === 'particle') return particleSubjects[effect.id] ?? `${effect.label.toLowerCase()} particles`;
  return `the ${displayEffectLabel(effect)} result`;
}

function resolveDescription(value, context) {
  return typeof value === 'function' ? value(context) : value;
}

