export function getParameterDescription(effect, parameter) {
  const context = {
    effect,
    parameter,
    effectLabel: displayEffectLabel(effect),
    subject: subjectFor(effect),
  };
  const override = effectOverrides[effect.id]?.[parameter.id];
  if (override) return resolveDescription(override, context);

  const shared = sharedDescriptions[parameter.id];
  if (shared && (preferShared.has(parameter.id) || !parameter.tooltip)) {
    return resolveDescription(shared, context);
  }

  if (typeof parameter.tooltip === 'string' && parameter.tooltip.trim()) {
    return parameter.tooltip.trim();
  }

  if (shared) return resolveDescription(shared, context);

  const label = String(parameter.label || parameter.id).trim();
  if (parameter.type === 'checkbox') {
    return `Turns ${label} on or off for ${displayEffectLabel(effect)}.`;
  }
  if (parameter.type === 'color') {
    return `Sets the color used by ${label} in ${displayEffectLabel(effect)}.`;
  }
  if (parameter.type === 'multi-select' || parameter.type === 'select') {
    return `Selects which ${label.toLowerCase()} options are used by ${displayEffectLabel(effect)}.`;
  }
  return `Adjusts ${label.toLowerCase()} for ${displayEffectLabel(effect)} and changes how that part of the effect appears on the canvas.`;
}

export function getEffectDisplayLabel(effect) {
  return displayEffectLabel(effect);
}
